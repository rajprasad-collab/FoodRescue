"use client";

import { useState } from "react";

const suggestedQuestions = [
  "Which donations need immediate redistribution?",
  "Explain the current self-healing route.",
  "Which algorithm is best for the current donation queue?",
  "When is the next synchronized collection window?",
];

export default function AIAssistantPage() {
  const [question, setQuestion] = useState("");
  const [messages, setMessages] = useState<
    { role: "user" | "assistant"; text: string }[]
  >([]);

  function askQuestion(text: string) {
    if (!text.trim()) return;

    setMessages((current) => [
      ...current,
      {
        role: "user",
        text,
      },
      {
        role: "assistant",
        text:
          "The FoodRescue AI assistant will analyze the results produced by the algorithm engine and provide an operational explanation. Gemini integration will be connected in the next development stage.",
      },
    ]);

    setQuestion("");
  }

  return (
    <div>
      {/* Header */}
      <div className="mb-8">
        <div className="text-xs font-medium uppercase tracking-[0.16em] text-[#8c918b]">
          Decision Support
        </div>

        <h2 className="mt-2 text-3xl font-semibold tracking-tight text-[#26352f]">
          FoodRescue Assistant
        </h2>

        <p className="mt-2 max-w-2xl text-sm leading-6 text-[#70766f]">
          Ask questions about donations, routes, priorities, algorithms and
          redistribution operations. The assistant will explain results
          generated by the FoodRescue algorithm engine.
        </p>
      </div>

      {/* Notice */}
      <div className="mb-6 flex items-start gap-3 rounded-lg border border-[#dce5df] bg-[#f3f7f4] p-4">
        <div className="flex h-7 w-7 shrink-0 items-center justify-center rounded-full bg-[#dce9e3] text-[#285547]">
          i
        </div>

        <div>
          <div className="text-sm font-semibold text-[#34413a]">
            Algorithm-first architecture
          </div>

          <p className="mt-1 text-xs leading-5 text-[#687069]">
            Python algorithms determine feasible routes, priorities and
            schedules. Gemini will explain and recommend using those results;
            it does not override operational constraints.
          </p>
        </div>
      </div>

      {/* Main panel */}
      <div className="grid gap-6 lg:grid-cols-[1fr_320px]">
        <section className="flex min-h-[560px] flex-col rounded-xl border border-[#e5e3dd] bg-white">
          {/* Conversation */}
          <div className="flex-1 p-6">
            {messages.length === 0 ? (
              <div className="flex h-full flex-col items-center justify-center text-center">
                <div className="flex h-14 w-14 items-center justify-center rounded-xl bg-[#e3eee9] text-2xl text-[#285547]">
                  ✦
                </div>

                <h3 className="mt-5 text-lg font-semibold text-[#34413a]">
                  How can I help with today's operations?
                </h3>

                <p className="mt-2 max-w-md text-sm leading-6 text-[#858a84]">
                  Ask a question about the current redistribution network,
                  donation priorities or algorithm results.
                </p>
              </div>
            ) : (
              <div className="space-y-5">
                {messages.map((message, index) => (
                  <div
                    key={index}
                    className={`flex ${
                      message.role === "user"
                        ? "justify-end"
                        : "justify-start"
                    }`}
                  >
                    <div
                      className={`max-w-[75%] rounded-lg px-4 py-3 text-sm leading-6 ${
                        message.role === "user"
                          ? "bg-[#173f35] text-white"
                          : "border border-[#e6e4de] bg-[#faf9f6] text-[#505851]"
                      }`}
                    >
                      {message.text}
                    </div>
                  </div>
                ))}
              </div>
            )}
          </div>

          {/* Input */}
          <div className="border-t border-[#e7e5df] p-4">
            <div className="flex gap-3">
              <input
                value={question}
                onChange={(event) => setQuestion(event.target.value)}
                onKeyDown={(event) => {
                  if (event.key === "Enter") {
                    askQuestion(question);
                  }
                }}
                placeholder="Ask about FoodRescue operations..."
                className="flex-1 rounded-lg border border-[#dddcd6] bg-[#faf9f6] px-4 py-3 text-sm outline-none transition placeholder:text-[#a1a39e] focus:border-[#7b9f91]"
              />

              <button
                onClick={() => askQuestion(question)}
                className="rounded-lg bg-[#173f35] px-5 py-3 text-sm font-medium text-white transition hover:bg-[#245748]"
              >
                Ask
              </button>
            </div>
          </div>
        </section>

        {/* Suggestions */}
        <aside>
          <div className="rounded-xl border border-[#e5e3dd] bg-white p-5">
            <div className="text-xs font-semibold uppercase tracking-[0.14em] text-[#8c918b]">
              Suggested questions
            </div>

            <div className="mt-4 space-y-2">
              {suggestedQuestions.map((item) => (
                <button
                  key={item}
                  onClick={() => askQuestion(item)}
                  className="w-full rounded-lg border border-[#e7e5df] bg-[#faf9f6] px-3 py-3 text-left text-xs leading-5 text-[#59615a] transition hover:border-[#b9cbc2] hover:bg-[#f2f6f3] hover:text-[#285547]"
                >
                  {item}
                </button>
              ))}
            </div>
          </div>

          <div className="mt-4 rounded-xl border border-[#e5e3dd] bg-white p-5">
            <div className="text-xs font-semibold uppercase tracking-[0.14em] text-[#8c918b]">
              Available context
            </div>

            <div className="mt-4 space-y-3 text-sm">
              <div className="flex justify-between">
                <span className="text-[#7b817a]">Donation priority</span>
                <span className="font-medium text-[#34413a]">Ready</span>
              </div>

              <div className="flex justify-between">
                <span className="text-[#7b817a]">Route engine</span>
                <span className="font-medium text-[#34413a]">Ready</span>
              </div>

              <div className="flex justify-between">
                <span className="text-[#7b817a]">Self-healing</span>
                <span className="font-medium text-[#34413a]">Ready</span>
              </div>

              <div className="flex justify-between">
                <span className="text-[#7b817a]">CRT scheduler</span>
                <span className="font-medium text-[#34413a]">Ready</span>
              </div>
            </div>
          </div>
        </aside>
      </div>
    </div>
  );
}